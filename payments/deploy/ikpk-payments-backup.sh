#!/usr/bin/env bash
# Резервная копия состояния платёжного сервиса (задача 4.3a, Решение 4а).
#
# Что копируется: хранилище сопоставлений `requestId ↔ платёж`, журнал исходов «нужна
# сверка», журнал canary материала ключа и выданные токены подтверждения. Всё это —
# состояние, восстановление которого нельзя заменить пересборкой: по нему сервис отличает
# «платёж уже создан» от «создаём впервые».
#
# Куда копируется: ОТДЕЛЬНЫЙ каталог, задаваемый `BACKUP_DIR`. Требование про отдельный
# раздел диска исполняется монтированием, а не этим скриптом: проверить «другой раздел» из
# скрипта можно только сравнением устройства, и это делается ниже — но как ПРЕДУПРЕЖДЕНИЕ,
# потому что на стенде отдельного раздела может не быть, а копия там всё равно лучше, чем
# её отсутствие. Молчать об этом нельзя: иначе «копия есть» прочитают как «копия на другом
# разделе».
#
# Атомарность: файл пишется во временное имя и переименовывается. Прерванная копия не
# оставляет полуфайла, который при восстановлении выглядел бы годным.
set -euo pipefail

DATA_DIR="${PAYMENT_DATA_DIR:-/var/lib/ikpk-payments}"
BACKUP_DIR="${BACKUP_DIR:-/var/backups/ikpk-payments}"
KEEP="${KEEP_BACKUPS:-42}"   # 42 копии по 4 часа ≈ 7 суток истории

if [[ ! -d "$DATA_DIR" ]]; then
  echo "backup: каталога состояния нет: $DATA_DIR — копировать нечего, это отказ, а не успех" >&2
  exit 1
fi

mkdir -p "$BACKUP_DIR"

# Предупреждение про раздел: сравниваем устройства, а не пути.
dev_data=$(df -P "$DATA_DIR" | awk 'NR==2 {print $1}')
dev_back=$(df -P "$BACKUP_DIR" | awk 'NR==2 {print $1}')
if [[ "$dev_data" == "$dev_back" ]]; then
  echo "backup: ВНИМАНИЕ — $BACKUP_DIR на том же устройстве ($dev_data), что и состояние." >&2
  echo "backup: копия защищает от повреждения файла, но не от потери раздела." >&2
fi

stamp=$(date -u +%Y%m%dT%H%M%SZ)
copied=0
for name in payments.json verification-journal.json hmac-canary.json duplicate-tokens.json; do
  src="$DATA_DIR/$name"
  [[ -f "$src" ]] || continue
  dst="$BACKUP_DIR/${stamp}.${name}"
  tmp="${dst}.part"
  cp -p -- "$src" "$tmp"
  mv -- "$tmp" "$dst"
  copied=$((copied + 1))
done

# Ноль скопированных файлов — это «проверить нечего», а не «всё в порядке»: сервис,
# создавший хотя бы один платёж, обязан иметь `payments.json`.
if (( copied == 0 )); then
  echo "backup: в $DATA_DIR не оказалось ни одного файла состояния — копия пуста, отказ" >&2
  exit 1
fi

# Уборка старых копий: по каждому имени оставляем последние $KEEP.
#
# Без `mapfile`: он появился в bash 4, а на macOS системный bash — 3.2, и скрипт падал бы
# при локальном прогоне проверки с «mapfile: command not found». Переносимость здесь не
# роскошь: поведенческий тест гоняется на машине разработчика, а не только на хосте.
for name in payments.json verification-journal.json hmac-canary.json duplicate-tokens.json; do
  # `|| true` в конце конвейера обязателен: при `set -o pipefail` пустой `ls` роняет весь
  # конвейер, и скрипт выходил с кодом 1 ПОСЛЕ успешного копирования — копия есть, а вызов
  # выглядит отказом. Ровно тот случай, когда сигнал врёт в обратную сторону.
  { ls -1t "$BACKUP_DIR"/*."$name" 2>/dev/null || true; } | tail -n +$((KEEP + 1)) | while IFS= read -r f; do
    [ -n "$f" ] && rm -f -- "$f"
  done
done

echo "backup: скопировано файлов: $copied, метка $stamp, каталог $BACKUP_DIR"
