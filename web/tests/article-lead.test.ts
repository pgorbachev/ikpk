import { describe, expect, it } from 'vitest';
import { articleLead } from '../src/lib/data';

/**
 * Лид карточки статьи снимает служебную шапку скрейпа и НЕ трогает обычный текст.
 *
 * Первые две редакции срезали части шапки по отдельности и портили содержание: дата
 * снималась без заголовка, заголовок — без даты. Оба примера ниже взяты из ревью и
 * зафиксированы регрессией, потому что оба выглядят как шапка ровно до первой проверки.
 */
describe('articleLead: шапка снимается целиком, текст не режется', () => {
  it('снимает шапку «Заголовок дата | Автор»', () => {
    expect(
      articleLead(
        'Беременность, роды и возможности остеопатии',
        'Беременность, роды и возможности остеопатии 20 янв., 2025 | Пилявский Сергей Орестович Период беременности важен.',
      ),
    ).toBe('Пилявский Сергей Орестович Период беременности важен.');
  });

  it('снимает шапку и с полным названием месяца, и с «г.»', () => {
    expect(articleLead('Отчёт', 'Отчёт 3 сентября 2016 г. | Tim Hutton Тело статьи.')).toBe('Tim Hutton Тело статьи.');
  });

  it('НЕ трогает дату, которая является содержанием статьи', () => {
    // Дата стоит в начале текста, но заголовок ей не предшествует — это не шапка.
    const text = '12 декабря 2007 г. в Бирюзовом зале прошла встреча православной общественности.';
    expect(articleLead('Встреча православной общественности с врачом-остеопатом', text)).toBe(text);
  });

  it('НЕ срезает подлежащее, совпавшее с заголовком', () => {
    // Заголовок совпал с первым словом предложения, но даты с разделителем за ним нет.
    const text = 'Психология помогает понять причины поведения.';
    expect(articleLead('Психология', text)).toBe(text);
  });

  it('НЕ трогает текст, если за заголовком идёт дата без разделителя', () => {
    const text = 'Хроника 5 мая 2024 года институт отметил юбилей.';
    expect(articleLead('Хроника', text)).toBe(text);
  });

  it('пустой заголовок не превращает начало текста в шапку', () => {
    const text = '20 янв., 2025 | Институт клинической прикладной кинезиологии Текст.';
    expect(articleLead('', text)).toBe(text);
  });

  it('схлопывает пробелы и снимает разметку', () => {
    expect(articleLead('Заголовок', '<p>Заголовок 1 мая 2025 | Автор</p>\n\n<p>Тело   статьи.</p>')).toBe('Автор Тело статьи.');
  });
});
