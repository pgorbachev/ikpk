import { describe, it, expect, beforeAll } from 'vitest';
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Тесты по спеке change `external-widgets` — ДОКУМЕНТ о персональных данных.
 *
 * Предмет — файл в репозитории (`web/public/terms/*.pdf`), а не вывод сборки. Отдельным
 * файлом, потому что у проверки отдельный ИНСТРУМЕНТ: текстовый слой снимается
 * `pdftotext`, и его отсутствие обязано читаться как «измерить не удалось», а не как
 * «нарушений нет». В общем файле это различие утонуло бы.
 *
 * Требование проверяемо автоматически именно потому, что документ содержит текстовый
 * слой: `proposal.md` называет это замером (`pdftotext` отдаёт «Пользовательское
 * соглашение и политика конфиденциальности»).
 */

const TERMS_DIR = join(import.meta.dirname, '..', 'public', 'terms');

let text: string;

beforeAll(() => {
  expect(existsSync(TERMS_DIR), `нет каталога '${TERMS_DIR}' — предмета проверки нет`).toBe(true);
  const pdfs = readdirSync(TERMS_DIR).filter((f) => f.toLowerCase().endsWith('.pdf'));
  expect(
    pdfs,
    'в public/terms нет ни одного PDF — документа о персональных данных на нашем домене нет',
  ).not.toEqual([]);

  let tool: string;
  try {
    tool = execFileSync('pdftotext', ['-v'], { encoding: 'utf-8', stdio: ['ignore', 'pipe', 'pipe'] });
  } catch (error) {
    // Ровно тот случай, который правила проекта требуют отличать от «нарушений нет»:
    // инструмента нет — значит проверка НЕ ВЫПОЛНЕНА.
    throw new Error(
      'pdftotext недоступен — текстовый слой документа снять нечем, проверка не выполнена ' +
        `(${(error as Error).message})`,
      { cause: error },
    );
  }
  void tool;

  text = pdfs
    .map((f) => execFileSync('pdftotext', [join(TERMS_DIR, f), '-'], { encoding: 'utf-8', maxBuffer: 32 * 1024 * 1024 }))
    .join('\n');

  // Сторож непустоты: утверждения ниже — про НАЛИЧИЕ, но пустой текст сделал бы их
  // отказом по неверной причине («в документе не назван чат» вместо «текст не снят»).
  expect(
    text.length,
    'текстовый слой документа пуст: документ выложен картинками, и требование «проверяемо ' +
      'автоматически» больше не выполняется',
  ).toBeGreaterThan(2000);
  expect(
    /персональн/i.test(text),
    'в снятом тексте нет слова «персональные» — снят не тот документ либо снят неверно',
  ).toBe(true);
});

describe('документ о персональных данных называет чат и чужую аналитику', () => {
  it('назван сбор данных через чат на сайте', () => {
    // Признак — НАЧАЛО слова, а не подстрока. Измерено: подстрока «чат» лежит внутри
    // слова «Получатель», которое в документе уже есть, — и проверка была зелёной, ничего
    // не проверив. `\b` здесь не годится: он опирается на класс \w, куда кириллица не
    // входит, поэтому граница слова определяется явным отрицательным просмотром назад.
    expect(
      /(?<![а-яёa-z])чат/iu.test(text),
      'документ не называет обращение через чат: чат — другая цель обработки, чем оплата, ' +
        'и из формулировки про оплату он не следует',
    ).toBe(true);
  });

  it('назван получатель данных из чата', () => {
    // Получатель — оператор портала, через который идёт чат. Признак — имя сервиса, а
    // не «слово рядом с чатом»: без получателя утверждение о цели неполно.
    expect(
      /bitrix|битрикс/i.test(text),
      'в документе не назван получатель данных, передаваемых через чат',
    ).toBe(true);
  });

  it('назван сторонний счётчик аналитики, работающий внутри виджета отзывов', () => {
    // Это НЕ наша обработка, но она происходит на нашей странице, и из формулировки про
    // оплату не следует ни она, ни чат.
    expect(/метрик/i.test(text), 'в документе не назван счётчик аналитики').toBe(true);
    expect(
      /виджет|отзыв/i.test(text),
      'счётчик назван, но не сказано, что он приходит внутри виджета отзывов: тогда ' +
        'непонятно, о чьей обработке речь',
    ).toBe(true);
  });
});
