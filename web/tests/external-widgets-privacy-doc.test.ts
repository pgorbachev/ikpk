import { describe, it, expect, beforeAll } from 'vitest';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { dist } from './helpers/dist-pages';

/**
 * Тесты по спеке change `external-widgets` — ДОКУМЕНТ о персональных данных.
 *
 * ── ПРЕДМЕТ СМЕНИЛСЯ: СТРАНИЦА ВМЕСТО PDF ──────────────────────────────────
 * Прежняя редакция снимала текстовый слой из `web/public/terms/*.pdf` через `pdftotext`.
 * Так было потому, что документ существовал только PDF-ом. Две причины сменить носитель, и
 * обе измерены:
 *
 * 1. Редактируемого исходника PDF не существует НИГДЕ. На старом сайте документ лежал тем
 *    же файлом на `storage.yandexcloud.net/ikpk-image/terms/`, HTML-страницы политики там не
 *    было вовсе — проверено по дампу контента discovery. То есть дополнить документ было
 *    нечем, и требование спеки не могло быть выполнено в принципе.
 * 2. `pdftotext` отсутствует на раннере GitHub (`spawnSync pdftotext ENOENT`, измерено на
 *    черновике PR #171). Проверка вела себя правильно — падала с «измерить не удалось», — но
 *    в обязательном прогоне была неисполнима без установки пакета.
 *
 * Теперь документ — страница на нашем домене, и предмет проверки — СОБРАННЫЙ вывод, а не
 * исходник компонента: спека требует документ, «размещённый на нашем домене», и страница,
 * не попавшая в сборку, этому не удовлетворяет. Текстовый слой у HTML есть по определению,
 * внешний инструмент не нужен, исход «измерить не удалось» остаётся построенным явно.
 *
 * PDF никуда не делся и по-прежнему лежит в `web/public/terms/`: он остаётся предыдущей
 * редакцией, на него ссылается сама страница. Его наличие проверяется отдельно — иначе
 * ссылка на него молча превратилась бы в 404.
 */

const PAGE = 'politika-konfidencialnosti';
const TERMS_DIR = join(import.meta.dirname, '..', 'public', 'terms');

let text: string;

/** Текст страницы без разметки: предмет утверждений — слова документа, а не теги. */
function textOf(html: string): string {
  return html
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/&laquo;|&raquo;/g, '"')
    .replace(/\s+/g, ' ');
}

beforeAll(() => {
  const file = join(dist, PAGE, 'index.html');
  expect(
    existsSync(file),
    `в сборке нет '${PAGE}/index.html' — документа о персональных данных на нашем домене ` +
      'нет, и проверять нечего',
  ).toBe(true);
  text = textOf(readFileSync(file, 'utf-8'));

  // Сторож непустоты: утверждения ниже — про НАЛИЧИЕ, и на пустом тексте они дали бы отказ
  // по неверной причине («в документе не назван чат» вместо «страница пуста»).
  expect(
    text.length,
    'текст страницы короче 2000 символов: это не документ, и требование «проверяемо ' +
      'автоматически» на нём ничего не значит',
  ).toBeGreaterThan(2000);
  expect(
    /персональн/i.test(text),
    'в тексте страницы нет слова «персональные» — собрана не та страница',
  ).toBe(true);
});

describe('документ о персональных данных называет чат и чужую аналитику', () => {
  it('назван сбор данных через чат на сайте', () => {
    // Признак — НАЧАЛО слова, а не подстрока. Измерено: подстрока «чат» лежит внутри слова
    // «Получатель», которое в документе уже есть, — и проверка была зелёной, ничего не
    // проверив. `\b` здесь не годится: он опирается на класс \w, куда кириллица не входит,
    // поэтому граница слова задана явным отрицательным просмотром назад.
    expect(
      /(?<![а-яёa-z])чат/iu.test(text),
      'документ не называет обращение через чат: чат — другая цель обработки, чем оплата, ' +
        'и из формулировки про оплату он не следует',
    ).toBe(true);
  });

  it('назван получатель данных из чата', () => {
    // Получатель — оператор платформы, через которую идёт чат. Признак — имя сервиса, а не
    // «слово рядом с чатом»: без получателя утверждение о цели неполно.
    expect(
      /bitrix|битрикс/i.test(text),
      'в документе не назван получатель данных, передаваемых через чат',
    ).toBe(true);
  });

  it('назван сторонний счётчик аналитики, работающий внутри виджета отзывов', () => {
    // Это НЕ наша обработка, но она происходит на нашей странице, и из формулировки про
    // оплату не следует ни она, ни чат.
    expect(/метрик/i.test(text), 'в документе не назван счётчик аналитики').toBe(true);
    expect(
      /виджет|отзыв/i.test(text),
      'счётчик назван, но не сказано, что он приходит внутри виджета отзывов: тогда ' +
        'непонятно, о чьей обработке речь',
    ).toBe(true);
  });

  it('чужой счётчик отличён от нашего по номеру, а не по слову «сторонний»', () => {
    // Без номеров «сторонний счётчик» — оценка, а не факт: их два, и путать их нельзя.
    // Замер спеки: внутри виджета работает Метрика 57020224, наш счётчик — 39506315
    // (`web/src/components/Analytics.astro:28`, `ym(39506315, 'init',`).
    expect(text, 'в документе не назван номер чужого счётчика внутри виджета').toContain('57020224');
    expect(text, 'в документе не назван номер собственного счётчика сайта').toContain('39506315');
  });
});

describe('прежняя редакция документа остаётся достижимой', () => {
  it('PDF на месте и страница на него ссылается', () => {
    // Ссылка на предыдущую редакцию — часть страницы. Если файл убрать, ссылка станет 404
    // молча: сборка о содержимом `public/` ничего не утверждает.
    expect(existsSync(TERMS_DIR), `нет каталога '${TERMS_DIR}'`).toBe(true);
    const pdfs = readdirSync(TERMS_DIR).filter((f) => f.toLowerCase().endsWith('.pdf'));
    expect(pdfs, 'в public/terms нет ни одного PDF, а страница на него ссылается').not.toEqual([]);

    const html = readFileSync(join(dist, PAGE, 'index.html'), 'utf-8');
    const hrefs = [...html.matchAll(/href="([^"]*\.pdf)"/gi)].map((m) => m[1]);
    expect(hrefs, 'на странице нет ссылки на PDF предыдущей редакции').not.toEqual([]);
    for (const href of hrefs) {
      const name = decodeURIComponent(href.replace(/^\/terms\//, ''));
      expect(
        pdfs.includes(name),
        `страница ссылается на '${href}', а такого файла в public/terms нет`,
      ).toBe(true);
    }
  });
});
