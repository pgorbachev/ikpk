/** Вхождения адреса загрузчика чата: хост берётся из конфигурации, а не угадывается. */
export function chatLoaderHits(html: string, loaderSrc: string) {
  const parsed = hostAndPath(loaderSrc);
  if (parsed === null)
    throw new Error(
      `адрес загрузчика чата '${loaderSrc}' не разбирается как адрес — проверять нечем`,
    );
  return embedAddressHits(html, { host: parsed.host, pathPrefix: parsed.path });
}

/**
 * Вхождения ЛЮБОГО адреса, похожего на загрузчик чата, а не только объявленного.
 *
 * Нужно сценарию «Умолчание не подставляется во втором и третьем состоянии»: его предмет
 * — «ни одного адреса загрузчика чата, ни известных порталов заказчика, ни любого
 * другого», а объявленного адреса в этих состояниях нет вовсе, значит признаком по нему
 * проверять нечего.
 *
 * Признак — ХОСТ поставщика виджета, а не имя атрибута и не форма пути: перечень
 * узнаваемых путей загрузчика был бы перечислением частных случаев, которое отстаёт от
 * предмета молча. Границу называю вслух: адрес загрузчика на хосте, не относящемся к
 * поставщику, этот признак не увидит — заранее проверить нечем, идентификатора загрузчика
 * у нас нет, и спека сама это фиксирует.
 */
export const CHAT_VENDOR_HOSTS = ['bitrix24.ru', 'bitrix24site.ru', 'bitrix24.com'] as const;

export function chatVendorHits(html: string): { tag: string; name: string; value: string }[] {
  return attributeValues(html).filter(({ value }) => {
    const parsed = hostAndPath(value);
    if (parsed === null) return false;
    return CHAT_VENDOR_HOSTS.some((h) => parsed.host === h || parsed.host.endsWith(`.${h}`));
  });
}

/**
 * Навигационный носитель адреса: переход посетителя, а не загрузка ресурса.
 *
 * Признак ПОЛОЖИТЕЛЬНЫЙ и узкий — это стандартный контракт HTML, а не перечень известных
 * мест нашей разметки: `href` у ссылки и `action` у формы. Всё остальное считается
 * загрузкой, и это направление выбрано намеренно: отрицательный признак не отстаёт от
 * предмета молча, а перечень «где у нас лежит загрузчик» отстал бы.
 */
export function isNavigationCarrier(tag: string, name: string): boolean {
  if ((tag === 'a' || tag === 'area') && name === 'href') return true;
  if (tag === 'form' && name === 'action') return true;
  return false;
}

/**
 * Вхождения адреса, ПОХОЖЕГО НА ЗАГРУЗЧИК ЧАТА, — по назначению, а не по домену.
 *
 * ── ПОЧЕМУ НЕ ПРОСТО «АДРЕС НА ХОСТЕ ПОСТАВЩИКА» ────────────────────────────
 * Потому что это ровно та ошибка, которой посвящено отдельное требование этой же спеки:
 * «проверка SHALL различать ссылку формы заявки и адрес загрузчика виджета по НАЗНАЧЕНИЮ,
 * а не по домену». Ссылки форм заявки живут на портале заказчика, то есть на том же
 * домене, что и возможный загрузчик.
 *
 * ИЗМЕРЕНО на боевом выводе (`npm run build`, 24.08.2026): адреса на хостах поставщика
 * несут **393 вхождения, и все до единого — `a[href]`**, ни одного другого носителя нет.
 * Признак «любой атрибут с этим хостом» краснел бы на 393 законных ссылках, то есть
 * проверка «умолчание не подставилось» была бы красной на исправном дереве — ложный отказ,
 * зеркало ложного зелёного.
 *
 * Отсюда признак: адрес на хосте поставщика в НЕнавигационном носителе. Первая редакция
 * этого модуля признака по назначению не имела, и обе проверки состояний 2 и 3 были
 * красны по причине, к их предмету не относящейся.
 */
export function chatLoaderSuspects(html: string): { tag: string; name: string; value: string }[] {
  return chatVendorHits(html).filter(({ tag, name }) => !isNavigationCarrier(tag, name));
}

/** Элементы с данным атрибутом-именем (наши объявленные точки). */
export function byDataName(html: string, name: string): Element[] {
  return [...walk(parseDocument(html))].filter((el) => attr(el, name) !== null);
}

/**
 * Числовая сводка отзывов: число, стоящее В СВЯЗКЕ со словом «отзыв», «оцен» или
 * «рейтинг».
 *
 * Признак назван спекой и намеренно НЕ «десятичная дробь»: на странице есть телефоны,
 * цены и даты. И он НЕ содержит сегодняшних значений — иначе был бы зелен при подмене
 * их другими числами.
 *
 * Окно ±40 символов, а не «тот же текстовый узел»: разметка вставляет числа в
 * отдельные элементы (`<b>4,9</b> <span>отзывов</span>`), и признак по узлу
 * пропустил бы ровно эту форму.
 */
const SUMMARY_STEMS = /отзыв|оцен|рейтинг/gi;
const NUMBER = /\d[\d.,\u00a0\u202f ]*/;

/**
 * Знак награды (`SEL_AWARD_ROW`) исключён из предмета: его подпись называет ГОД
 * знака (например, «Хорошее место 2026»), а не число отзывов или рейтинг, но в
 * развёрнутом тексте страницы он может оказаться в 40 символах от слова «отзыв» —
 * не потому что описывает то же самое, а потому что элементы смежны в разметке.
 * Окно вокруг стем-слова этого не различает, дерево — различает.
 */
export function ratingSummaryHits(html: string): string[] {
  const doc = parseDocument(html);
  return ratingSummaryHitsInText(textOfExcluding(doc, (el) => attr(el, SEL_AWARD_ROW) !== null));
}

export function ratingSummaryHitsInText(text: string): string[] {
  const out: string[] = [];
  for (const stem of text.matchAll(SUMMARY_STEMS)) {
    const at = stem.index ?? 0;
    const window = text.slice(Math.max(0, at - 40), Math.min(text.length, at + stem[0].length + 40));
    if (NUMBER.test(window)) out.push(window.trim());
  }
  return [...new Set(out)];
}

/**
 * Признак «полоса часов работы»: диапазон вида `10:00 … 18:00` в видимом тексте.
 *
 * Признак НЕ применяется ко всей странице, и это существенно: страницы семинаров
 * называют время занятий теми же числами, и проверка по всей странице краснела бы от
 * исправного содержимого. Предмет — только поддерево НАШЕГО фасада чата, где такой
 * полосы быть не должно вовсе.
 */
export function hoursStripText(el: Element): string | null {
  const text = textOf(el);
  return /\b10[:.]\d\d\b/.test(text) && /\b18[:.]\d\d\b/.test(text) ? text : null;
}

/** Видимый текст поддерева элемента — для проверок содержимого секции. */
export function elementText(el: Element): string {
  return textOf(el);
}

/** Все элементы документа: нужно проверкам, судящим по составу поддерева. */
export function elements(html: string): Element[] {
  return [...walk(parseDocument(html))];
}

/** Потомки элемента, включая его самого. */
export function subtree(el: Element): Element[] {
  return [el, ...walk(el)];
}

/** Ссылки `tel:` в поддереве — гарантия, остающаяся при неответившем загрузчике. */
export function telLinks(el: Element): string[] {
  return subtree(el)
    .filter((node) => node.tagName === 'a')
    .map((node) => attr(node, 'href') ?? '')
    .filter((href) => href.startsWith('tel:'));
}
