/**
 * Утверждение об исходе fail-closed старта платёжного сервиса.
 *
 * ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ, а не три `expect` на месте. Прежние проверки писали так:
 *
 *     expect(r.listening).toBe(false);
 *     expect(r.connection).toBe('refused');
 *     expect(r.exitCode).not.toBe(0);
 *
 * и были ЗЕЛЁНЫМИ на процессе, который просто не успел подняться: обвязка ждала
 * фиксированные 1500 мс и отдавала `child.exitCode`, то есть `null` у живого процесса, а
 * `null !== 0` условие «код не ноль» удовлетворяет. Наблюдаемое следствие — плавающее
 * число красных между двумя одинаковыми прогонами (41 против 40 на
 * `4.10 … prod с ТЕСТОВЫМ магазином не открывает порт`). То есть отсутствие слушателя
 * выдавалось за подтверждённый отказ, а «я не смогла измерить» — за «дефектов нет».
 *
 * ЧТО ЗДЕСЬ УТВЕРЖДАЕТСЯ, и каждый пункт — про свой способ обмануться:
 *  1. процесс ФАКТИЧЕСКИ завершился в пределах deadline (`outcome === 'exited'`);
 *     `timeout` — отказ проверки, а не подтверждение fail-closed;
 *  2. код выхода — ненулевое ЧИСЛО, а не `null`;
 *  3. порт не открыт и соединение отвергнуто — то, что проверялось и раньше;
 *  4. причина названа СЕМАНТИЧЕСКИ: в выводе процесса есть имя переменной или предмет
 *     отказа. Без этого «упал с кодом 1» неотличимо от падения по любой посторонней
 *     причине — опечатке в обвязке, отсутствующем модуле, чужом порте.
 *
 * `allowTimeout: true` передаётся здесь НАМЕРЕННО: предмет этой функции — сам исход,
 * поэтому исключение из обвязки (которое она поднимает по умолчанию) заменило бы
 * названное утверждение безымянным. Всем остальным вызывающим `spawnPaymentProcess`
 * timeout по-прежнему приходит исключением.
 */

import { expect } from 'vitest';
import { spawnPaymentProcess, type SpawnResult } from './payment-service';

export type FailClosedReason = RegExp | readonly RegExp[];

/**
 * Запустить процесс с заданным окружением и утвердить fail-closed исход.
 *
 * @param what   чем именно нарушено окружение — попадает в сообщения об отказе
 * @param env    полное окружение процесса
 * @param reason признаки причины в выводе процесса; достаточно СОВПАДЕНИЯ ОДНОГО из них
 */
export async function expectFailClosedStart(
  what: string,
  env: Record<string, string>,
  reason: FailClosedReason,
): Promise<SpawnResult> {
  const r = await spawnPaymentProcess({ env, allowTimeout: true });
  const output = `${r.stderr}${r.stdout}`;
  const tail = output.trim().slice(0, 400) || '<пусто>';

  // Сообщение называет ФАКТИЧЕСКИЙ исход, а не предполагает один из двух: «поднялся и
  // слушает» и «не подал признаков ни в одну сторону» — разные отказы, и общий текст про
  // таймаут во втором случае врал бы о том, что измерено.
  expect(
    r.outcome,
    r.outcome === 'listening'
      ? `${what}: процесс поднялся и отвечает на своём порту (соединение ${r.connection}) — ` +
        `fail-closed не сработал вовсе.\nвывод: ${tail}`
      : `${what}: процесс за ${r.deadlineMs} мс не завершился и не открыл порт (ждали ${r.waitedMs} мс). ` +
        'Это непройденное измерение, а не подтверждённый отказ: «порт не открыт» у ещё не ' +
        `поднявшегося процесса ничего не значит.\nвывод: ${tail}`,
  ).toBe('exited');

  expect(
    typeof r.exitCode,
    `${what}: кода выхода нет (${JSON.stringify(r.exitCode)}, сигнал ${JSON.stringify(r.signal)}) — ` +
      'процесс не завершился сам. Проверка «код не ноль» на этом значении проходит всегда.',
  ).toBe('number');
  expect(r.exitCode, `${what}: процесс завершился успешно, то есть fail-closed не сработал`).not.toBe(0);

  expect(r.listening, `${what}: порт открыт\nвывод: ${tail}`).toBe(false);
  expect(r.connection, `${what}: соединение не отвергнуто`).toBe('refused');

  const reasons = Array.isArray(reason) ? reason : [reason];
  expect(
    reasons.some((re) => re.test(output)),
    `${what}: процесс упал (код ${r.exitCode}), но причину не назвал — ни один из признаков ` +
      `${reasons.map(String).join(', ')} в выводе не встретился. Падение по посторонней ` +
      `причине выглядит точно так же.\nвывод: ${tail}`,
  ).toBe(true);

  return r;
}
