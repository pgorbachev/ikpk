/**
 * Контраст по WCAG: относительная яркость и отношение двух цветов.
 *
 * Формулы вынесены из `a11y.spec.ts`, где они были объявлены внутри одного describe.
 * Причина не в сокращении строк: гейтов над контрастом стало два (контролы шапки и текст
 * ошибки платёжной формы), они живут в разных наборах и над разными артефактами, а две
 * копии одной формулы — это ровно тот случай, когда две проверки над одним предметом
 * начинают отвечать по-разному и ни одна об этом не узнаёт.
 *
 * Цвета приходят из `getComputedStyle`, то есть строкой `rgb(...)`/`rgba(...)`: мерить надо
 * ВЫЧИСЛЕННЫЙ цвет, а не написание токена в CSS — иначе переопределение темой гейт не
 * заметит (в проекте это уже было).
 */

/** Относительная яркость по WCAG 2.x для канала 0..255. */
export function luminance([r, g, b]: number[]): number {
  const f = (c: number): number => {
    const v = c / 255;
    return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
}

/** Отношение контраста двух цветов; порядок аргументов не важен. */
export function contrastRatio(a: number[], b: number[]): number {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

/**
 * `rgb(31, 36, 31)` → `[31, 36, 31]`. Альфа отбрасывается: полупрозрачный текст поверх
 * известного фона здесь не встречается, а молча смешивать его с догадкой о подложке
 * значило бы выдавать выдуманное число за измеренное.
 */
export function parseRgb(color: string): number[] {
  return (color.match(/\d+(\.\d+)?/g) ?? ['0', '0', '0']).slice(0, 3).map(Number);
}

// ─── Цвет графического объекта: доминирующая заливка и цветовое расстояние ───────────
// Дописано здесь, а не отдельным модулем, по требованию change `social-accounts`
// (`tasks.md`, 3.11): отношение контраста тут уже есть, а измерения ГРАФИЧЕСКОГО объекта
// не было. Две копии формул над одним предметом — ровно тот случай, когда две проверки
// начинают отвечать по-разному и ни одна об этом не узнаёт.
//
// Без новых зависимостей (`design.md`, Решение 13): перевод sRGB → Lab и расстояние — это
// десятки строк, а новая зависимость тянет два обязательных контекста.

/** sRGB 0..255 → линейный 0..1. Та же передаточная функция, что в `luminance` выше. */
function toLinear(c: number): number {
  const v = c / 255;
  return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
}

/** CIE Lab (D65) из sRGB. */
export function srgbToLab([r, g, b]: number[]): [number, number, number] {
  const [rl, gl, bl] = [toLinear(r), toLinear(g), toLinear(b)];
  // Матрица sRGB → XYZ (D65); координаты нормированы на белую точку D65.
  const x = (0.4124564 * rl + 0.3575761 * gl + 0.1804375 * bl) / 0.95047;
  const y = 0.2126729 * rl + 0.7151522 * gl + 0.072175 * bl;
  const z = (0.0193339 * rl + 0.119192 * gl + 0.9503041 * bl) / 1.08883;
  const f = (t: number): number => (t > 216 / 24389 ? Math.cbrt(t) : (841 / 108) * t + 4 / 29);
  const [fx, fy, fz] = [f(x), f(y), f(z)];
  return [116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)];
}

/**
 * Цветовое расстояние ΔE76 (евклидово в CIE Lab).
 *
 * МЕТРИКА НАЗВАНА, потому что без неё порог не является критерием: евклидово расстояние в
 * sRGB, ΔE76 и ΔE2000 дают разный порядок на тех же парах. Спека метрику не называет — это
 * ДЕФЕКТ-4 разбора (`docs/handoff/social-accounts-spec-executability.md`), и выбор здесь —
 * решение исполнителя, а не вывод из спеки. ΔE76 взят потому, что он воспроизводим без
 * зависимости и не зависит от порядка аргументов.
 */
export function deltaE76(a: number[], b: number[]): number {
  const [la, aa, ba] = srgbToLab(a);
  const [lb, ab, bb] = srgbToLab(b);
  return Math.hypot(la - lb, aa - ab, ba - bb);
}

/**
 * Порог цветового расстояния между марками двух видеосервисов. РЕШЕНИЕ ИСПОЛНИТЕЛЯ: в
 * спеке порога нет, а требование велит его объявить (ДЕФЕКТ-4 разбора).
 *
 * Он поставлен между двумя ИЗМЕРЕННЫМИ величинами, а не выбран на глаз: контрольная пара
 * `#ff0000` / `#cc0000` даёт **19,4**, а фирменные цвета двух видеосервисов, зафиксированные
 * в репозитории мокапом (`#ff0000` против `#e11e6a`), — **58,8**. Порог 25 лежит между. Оба
 * числа печатает сам тест, когда краснеет.
 *
 * Границу надо знать: цвета мокапные, а не официальные. Официальных марок в репозитории на
 * момент написания теста нет, поэтому 58,8 — оценка порядка, и после задачи 3.10 число
 * снимается заново на настоящих марках.
 */
export const COLOR_DISTANCE_THRESHOLD = 25;

/**
 * Контрольная пара: фирменный красный Youtube и его же более тёмный оттенок — тот же тон,
 * умноженный на 0,8 по каждому каналу. Пара получена ПРЕОБРАЗОВАНИЕМ одного цвета, а не
 * подбором: иначе «два оттенка одного фирменного цвета» означало бы «любые два значения,
 * которые мне удобны», и подтверждение порога стало бы выбором исполнителя.
 */
export const CONTROL_PAIR = {
  a: [255, 0, 0] as number[],
  b: [204, 0, 0] as number[],
};

/**
 * Доминирующая заливка марки: цвет наибольшей доли НЕПРОЗРАЧНЫХ пикселей.
 *
 * Полупрозрачный пиксель композитится с фоном подвала соответствующей темы — этого прямо
 * требует спека, иначе «цвет марки» неизмерим у марки с прозрачностью. Полностью
 * прозрачные (alpha 0) пиксели в счёт не идут: они не часть марки.
 *
 * Возвращает `null`, когда непрозрачных пикселей нет вовсе. Это «измерить не удалось», а не
 * «нарушений нет», и вызывающая проверка обязана падать, а не проходить.
 */
export function dominantOpaqueRgb(
  rgba: ArrayLike<number>,
  background: number[],
): { rgb: number[]; share: number; opaquePixels: number } | null {
  const counts = new Map<string, number>();
  let opaque = 0;
  for (let i = 0; i + 3 < rgba.length; i += 4) {
    const alpha = rgba[i + 3]!;
    if (alpha === 0) continue;
    opaque += 1;
    const pixel = [rgba[i]!, rgba[i + 1]!, rgba[i + 2]!];
    const key = (alpha === 255 ? pixel : composite(pixel, alpha, background)).join(',');
    counts.set(key, (counts.get(key) ?? 0) + 1);
  }
  if (opaque === 0) return null;
  let best = '';
  let bestCount = 0;
  for (const [key, n] of counts) {
    if (n > bestCount) {
      best = key;
      bestCount = n;
    }
  }
  return { rgb: best.split(',').map(Number), share: bestCount / opaque, opaquePixels: opaque };
}

function composite(rgb: number[], alpha: number, background: number[]): number[] {
  const a = alpha / 255;
  return rgb.map((c, i) => Math.round(c * a + (background[i] ?? 0) * (1 - a)));
}
