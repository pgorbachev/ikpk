import { getViteConfig } from 'astro/config';

// ─── НОВАЯ ИНФРАСТРУКТУРА, объявляется вслух ─────────────────────────────────
// Это первый в проекте прогон, который РЕНДЕРИТ Astro-компонент вне сборки сайта
// (Astro Container API). До сих пор о разметке судили только по собранному `dist`, и у
// этого есть предел: `dist` показывает единственное состояние данных — то, что лежит в
// снапшоте. Состояние «месяцев нет ни одного» на реальных данных не наступает, поэтому
// требование «контрол месяца присутствует в разметке ВСЕГДА» ни одним гейтом не
// проверялось: dist-гейт видит только непустой список, а браузерная проверка
// `@month-empty-list` монтирует свою разметку и измеряет скрипт, а не шаблон.
//
// Отдельная конфигурация нужна по технической причине: компонент `.astro` без
// vite-плагина Astro не разбирается вовсе («Failed to parse source for import analysis»),
// а тянуть плагин в основную юнит-конфигурацию значит менять конвейер преобразования всем
// восемнадцати файлам тестов ради одного. Конфигурация подключается к `npm test`
// вторым шагом, поэтому прогон остаётся внутри workflow `Tests`, то есть внутри гейта
// публикации.
// Экспортируется ПЛОСКИЙ объект, а не функция, которую отдаёт `getViteConfig`. Причина не
// в стиле: два существующих гейта читают конфигурации vitest импортом и разбирают секцию
// `test` (`tests/repo-hygiene.test.ts` — сверку списков включений и исключений,
// `tests/demo-gate.test.ts` — какой конфиг какой каталог читает). Функция им непонятна, и
// оба падали бы с «не отдаёт объект конфигурации» — то есть новая конфигурация ослепила бы
// проверки, которые следят за тем, что ни один тест не потерялся.
export default await getViteConfig({
  test: {
    include: ['tests/schedule-filters.render.test.ts', 'tests/rich-content-render.test.ts'],
  },
})({ command: 'serve', mode: 'test' });
