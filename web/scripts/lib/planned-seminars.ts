/**
 * Какие семинары считаются запланированными — по расписанию, а не по полю
 * `events`.
 *
 * `events` у семинара означает, что событие когда-либо существовало, включая
 * прошедшие: по нему статус planned получали 107 семинаров при 47 реально
 * имеющих будущие даты. Ложный «запланирован» хуже отсутствия статуса — человек
 * идёт искать даты, которых нет.
 *
 * Дата передаётся аргументом, а не берётся из `new Date()` внутри. Причина не
 * стилистическая: пока функция читала календарь сама, проверить её можно было
 * только на живых данных, и такая проверка краснела от простого хода времени —
 * 3 августа 2026 года гейт `catalog-data` упал на семинаре, чья единственная
 * дата прошла 29 июля, при полностью исправном коде. Теперь логика проверяется
 * фикстурами с фиксированной датой, а календарь остаётся заботой вызывающего.
 */

export interface ScheduleEntryLike {
  status?: string;
  startAt?: string;
  endAt?: string;
  seminar?: { slug?: string } | null;
}

/**
 * Последний день события в виде календарной даты.
 *
 * Сравниваем КАЛЕНДАРНЫЕ даты, а не полные метки времени: `startAt` хранится с
 * временем 00:00, поэтому уже в 00:01 дня проведения полное сравнение давало
 * «в прошлом», и идущий сегодня семинар превращался в «Даты уточняются». Берём
 * `endAt`, если он позже: у 60 событий обучение длится несколько дней, и всё это
 * время оно актуально.
 */
export function lastDay(entry: ScheduleEntryLike): string {
  const start = entry.startAt ?? '';
  const end = entry.endAt ?? '';
  return (end > start ? end : start).slice(0, 10);
}

/**
 * Слаги семинаров, у которых по расписанию есть день не раньше `today`.
 *
 * @param today календарная дата в виде `YYYY-MM-DD`
 */
export function plannedSlugs(entries: ScheduleEntryLike[], today: string): Set<string> {
  return new Set(
    entries
      .filter((e) => e.status === 'active' && lastDay(e) >= today && e.seminar?.slug)
      .map((e) => e.seminar!.slug!),
  );
}

/** Календарная дата «сегодня» для вызывающего, которому нужен реальный день. */
export const calendarToday = (): string => new Date().toISOString().slice(0, 10);
