// Конфигурация ТОЛЬКО для `astro preview` над артефактом роли `stand` (задача 6.15).
//
// Зачем отдельный файл — та же причина, что у astro.demo.config.mjs: `astro build` умеет
// `--outDir` и собирает стенд в `dist-stand` из командной строки (`npm run build:stand`), а у
// `astro preview` флага `--outDir` НЕТ — он берёт `outDir` из конфигурации, а неизвестные
// флаги принимает молча и поднимает сервер над боевым `dist`. Проверено на демо-случае:
// сервер, запущенный с `--outDir`, отдавал чужой артефакт, то есть предмет проверки
// подменялся молча.
//
// Роль здесь НЕ задаётся: роль — свойство СБОРКИ (`PAYMENT_ROLE`, скрипт `build:stand`), а
// не раздачи. Этот файл только выбирает, какой каталог отдавать. То, что отданный артефакт
// действительно объявляет роль `stand`, проверяет сам набор
// (`tests/payment-form.spec.ts`, 6.15) — и сегодня он на этом красный.
//
// Конфигурация обязана лежать внутри `web/`: путь к ней разрешается относительно корня
// проекта, и файл снаружи не загружается.
