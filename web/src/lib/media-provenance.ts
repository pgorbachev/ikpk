/**
 * Происхождение изображений: подлинный материал ИКПК или сток.
 *
 * Нужно для прототипов каркаса. Проверено просмотром самих файлов, а не по
 * именам:
 *
 *   портреты преподавателей   ПОДЛИННЫЕ. Реальные люди: врач с анатомической
 *                             моделью крестца и позвоночника на студийном фоне,
 *                             врач в халате у ровной светлой стены. Часть — с
 *                             заменённым синтетическим фоном.
 *   изображения институтов    сток и CGI: глянцевое спа-фото модели на
 *                             массажном столе, анатомические манекены,
 *                             3D-рендеры.
 *   изображения событий       сток и клипарт: силуэт в прыжке на закате с
 *                             разорванной цепью.
 *   изображения статей        сток: крупнейший файл библиотеки, 3520×1980, —
 *                             фотография еды.
 *   логотипы и эмблемы        подлинные знаки бренда.
 *
 * Зачем помечать в прототипе: без пометки владелец оценит стоковую картинку как
 * собственную съёмку института и выберет вариант, которого потом не получит.
 * Снимков занятий, залов и работы в парах не существует ни в каком разрешении —
 * поэтому направление не имеет права держаться на них.
 */

export type Provenance = 'authentic' | 'stock' | 'brand';

/** Портреты преподавателей лежат в media/users/**; они и есть фотоактив ИКПК. */
const TEACHER_PORTRAITS = /\/media\/users\/\d+\/images\//;

/** Логотипы и эмблемы институтов, иконки ведомств. */
const BRAND = /\/media\/legacy\/|logo|emblem|icon/i;

export function provenanceOf(src: string): Provenance {
  if (BRAND.test(src)) return 'brand';

  // Осознанное упрощение: в media/users/** лежат и портреты, и часть контентных
  // картинок. Точную принадлежность даёт связь с сущностью (у преподавателя поле
  // photo), поэтому классификатор используется ВМЕСТЕ с проверкой в разметке:
  // портретом считается только то, что выводится в карточке преподавателя.
  if (TEACHER_PORTRAITS.test(src)) return 'authentic';

  return 'stock';
}

