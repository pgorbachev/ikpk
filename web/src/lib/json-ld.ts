/**
 * Сериализация JSON-LD для вставки в <script type="application/ld+json">.
 *
 * Почему не голый `JSON.stringify`: он экранирует кавычки JSON, но последовательность
 * `</script>` оставляет как есть. Строка с ней закрывает тег прямо внутри значения, и всё
 * последующее браузер разбирает как разметку — то есть содержимое данных превращается в
 * исполняемый HTML.
 *
 * Лечится заменой каждого `<` на JSON-escape `<`. Для разбора это тот же символ
 * (`JSON.parse` вернёт исходную строку), но в тексте страницы закрывающего тега больше
 * не возникает. Экранировать `/` не требуется: без `<` последовательность не собирается.
 */
export function serializeJsonLd(schema: unknown): string {
  return JSON.stringify(schema).replace(/</g, '\\u003c');
}
