// Знак награды сторонней площадки: выводится ОФИЦИАЛЬНЫМ встраиванием сервиса, а не
// нашей отрисовкой.
//
// Прежняя редакция рисовала марку сама и требовала для этого четыре поля данных — год
// действия, источник, свидетельство награждения и свидетельство права размещать марку.
// Конструкция стояла на утверждении спеки, что «ни Яндекс, ни 2ГИС цифрового знака для
// сайта не выдают». Утверждение было внесено без проверки и опровергнуто замером
// 2026-09-05: `https://yandex.ru/sprav/widget/rating-badge/<id>?type=award` отвечает 200
// и отдаёт официальный знак с живым рейтингом. Все три поля сняты вместе с копией: они
// существовали, чтобы НАША отрисовка не утверждала непроверенного, а утверждает теперь
// сервис.
//
// Года в официальном знаке нет, и прежний предохранитель (гасить при несовпадении года
// со сборкой) заменён чужим и более верным: сервис сам убирает знак с карточки, когда
// награда кончается, и встраивание это отражает.

export type AwardProviderId = 'yandex-maps' | '2gis';

export interface AwardBadgeDeclaration {
  /** Площадка, выдавшая награду. */
  provider: AwardProviderId;
  /**
   * Идентификатор организации в этой площадке. Пусто — знак не показывается: без
   * карточки знак приписал бы институту чужую репутацию.
   */
  orgId: string | null;
  /** Доступное имя встраивания. Видимый текст рисует сам сервис. */
  title: string;
}

/** Адрес официального встраивания знака. `null` — у площадки его нет либо он не проверен. */
export function badgeEmbedSrc(badge: AwardBadgeDeclaration): string | null {
  if (!isDeclared(badge.orgId)) return null;
  // Замерено 2026-09-05: кадр 150×50, варианты `type=alt` и `theme=dark`. Источник —
  // «О компании → Промоматериалы» в Яндекс Бизнесе.
  if (badge.provider === 'yandex-maps')
    return `https://yandex.ru/sprav/widget/rating-badge/${badge.orgId}?type=award`;
  // У 2ГИС официальное встраивание знака НЕ ПРОВЕРЕНО — карточки ИКПК там нет, измерять
  // было нечего (`docs/client-requests.md`, пункты 13, 23, 24). Утверждать, что его не
  // существует, нельзя: ровно такое непроверенное утверждение про Яндекс уже стояло в
  // спеке и оказалось ложным.
  return null;
}

function isDeclared(value: string | null | undefined): value is string {
  return typeof value === 'string' && value.trim() !== '';
}

/** Знаки, которые страница вправе показать: объявлен идентификатор и есть встраивание. */
export function visibleAwardBadges(
  declared: readonly AwardBadgeDeclaration[],
): AwardBadgeDeclaration[] {
  return declared.filter((badge) => badgeEmbedSrc(badge) !== null);
}

