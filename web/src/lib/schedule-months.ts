/**
 * Месяцы записи расписания: вывод на этапе сборки.
 *
 * Зачем отдельный модуль. Месяц — единственное измерение фильтров, которое надо
 * ВЫВЕСТИ, а не взять из данных готовым. Вывод живёт здесь, чтобы о времени судило
 * одно место: клиентский скрипт получает месяц признаком карточки и ничего не
 * вычисляет. Наивная реализация сравнивала бы дату карточки с выбранным значением в
 * браузере — тогда о времени судят сборка и скрипт, и расходятся они не сразу и не
 * заметно.
 *
 * Опорная дата приходит АРГУМЕНТОМ, а не берётся из окружения: иначе проверку нельзя
 * написать фикстурами, и она краснела бы от хода времени при исправном коде. В
 * проекте это уже случалось — с гейтом статуса семинара и с гейтом catalog-data.
 *
 * Последний день события берётся из `schedule-window`, а не выводится заново: правило
 * «endAt раньше startAt — значит последний день это startAt» уже реализовано там, и
 * второе его место разошлось бы с первым.
 *
 * Арифметика месяцев — на строках `YYYY-MM`, без объектов даты. Причина не в
 * экономии: объект даты вносит часовой пояс сборочной машины, тогда как ключ выведен
 * по UTC. Расхождение было бы ровно в один месяц и ровно на границе — то есть
 * проявлялось бы редко и выглядело бы как случайность. Лексикографическое сравнение
 * `YYYY-MM` совпадает с хронологическим, поэтому сортировка и выбор максимума делаются
 * прямо на строках.
 */

import { lastDay, type ScheduleWindowEntry } from './schedule-window';

/** Месяц в списке предложенных: ключ и сколько записей в нём идёт. */
export interface MonthOption {
  key: string;
  count: number;
}

/**
 * Названия месяцев таблицей, а не библиотекой локализации.
 *
 * `Intl` в русской локали при запросе месяца вместе с годом даёт «сентябрь 2026 г.» —
 * строчную букву и приписку «г.», то есть готовый вывод требованию не удовлетворяет.
 * Вдобавок он зависит от версии ICU в сборочном окружении.
 */
const MONTH_NAMES = [
  'Январь',
  'Февраль',
  'Март',
  'Апрель',
  'Май',
  'Июнь',
  'Июль',
  'Август',
  'Сентябрь',
  'Октябрь',
  'Ноябрь',
  'Декабрь',
];

/** Ключ месяца `YYYY-MM` из календарной даты или метки времени `YYYY-MM-DD…`. */
const monthOf = (value: string): string => value.slice(0, 7);

/** Следующий календарный месяц. Год переносится вручную: `12 + 1` — это январь. */
function nextMonth(key: string): string {
  const year = Number(key.slice(0, 4));
  const month = Number(key.slice(5, 7));
  if (month >= 12) return `${year + 1}-01`;
  return `${year}-${String(month + 1).padStart(2, '0')}`;
}

/**
 * Ключи месяцев записи — от месяца начала до месяца последнего дня включительно.
 *
 * Событие относится ко ВСЕМ месяцам, в которых идёт, а не только к месяцу начала:
 * разбиение по началу потеряло бы семинар 29 октября — 1 ноября в ноябре, хотя
 * большая его часть идёт в ноябре. Тот же дефект уже случался в другой проекции —
 * фильтр по первому дню убирал идущий многодневный семинар со страницы.
 *
 * Отсечение прошлых месяцев — ЧАСТЬ этого вывода, а не отдельный шаг над готовым
 * списком. Иначе у карточки остаётся ключ, которого нет в списке предложенных
 * месяцев, и два требования спеки противоречат друг другу.
 *
 * Хотя бы один ключ остаётся всегда, и это следует из инварианта, а не из данных:
 * запись прошла окно актуальности, значит её последний день не раньше опорной даты,
 * значит месяц последнего дня не раньше месяца опорной даты.
 *
 * Записи без `startAt` начало берётся из последнего дня, то есть ключ у неё ровно
 * один. Тип поле допускает необязательным (`schedule-window`), и без этой оговорки
 * пустая строка сравнивалась бы с отсечкой как «раньше любого месяца» — запись
 * получала бы ключ на КАЖДЫЙ месяц от опорной даты до `endAt` и находилась бы выбором
 * месяцев, в которых о ней ничего не известно. В сегодняшних данных таких записей нет
 * (63 из 63 с `startAt`), поэтому это защита от аномалии чужого API, а не описание
 * наблюдённого случая.
 */
export function monthKeys(entry: ScheduleWindowEntry, today: string): string[] {
  const last = monthOf(lastDay(entry));
  const start = entry.startAt ? monthOf(entry.startAt) : last;
  const cutoff = monthOf(today);
  if (last === '' || last < cutoff) return [];

  const keys: string[] = [];
  let key = start > cutoff ? start : cutoff;
  while (key <= last) {
    keys.push(key);
    key = nextMonth(key);
  }
  return keys;
}

/**
 * Предложенные месяцы: объединение ключей записей по возрастанию.
 *
 * Список — НЕ непрерывный интервал: месяц без записей в него не попадает, в том числе
 * месяц внутри диапазона. Объединение берётся над уже отсечёнными ключами, поэтому
 * второго правила отбора здесь нет.
 *
 * `count` — сколько записей ИДЁТ в этом месяце, а не доля разбиения: запись через
 * границу учитывается в обоих месяцах. Поэтому сумма `count` больше числа записей на
 * число пересечённых границ, и проверка «сумма равна числу записей» была бы красной на
 * исправном коде.
 */
export function monthOptions(entries: ScheduleWindowEntry[], today: string): MonthOption[] {
  const counts = new Map<string, number>();
  for (const entry of entries) {
    for (const key of monthKeys(entry, today)) {
      counts.set(key, (counts.get(key) ?? 0) + 1);
    }
  }
  return [...counts.entries()]
    .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
    .map(([key, count]) => ({ key, count }));
}

/**
 * Подпись месяца: «Сентябрь 2026», с числом записей — «Сентябрь 2026 (15)».
 *
 * Выводится из самого ключа, без обращения к текущему времени: иначе подпись нельзя
 * проверить фикстурами. Число записей — второй носитель того же факта, поэтому оно
 * обязано совпадать с фактической выдачей месяца; расхождение ловится проверкой, а не
 * глазами.
 */
export function monthLabel(key: string, count?: number): string {
  const year = key.slice(0, 4);
  const name = MONTH_NAMES[Number(key.slice(5, 7)) - 1] ?? key;
  const label = `${name} ${year}`;
  return count === undefined ? label : `${label} (${count})`;
}
