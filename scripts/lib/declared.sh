# Разбор объявленного состояния. Общий для провижининга, проверки и восстановления:
# три БАЙТОВО одинаковые копии этой функции разошлись бы молча, и тогда применение и
# проверка читали бы одно и то же объявление по-разному — расхождение, которое не ловится
# ничем автоматическим.
#
# Провижининг не подключает файл через `source`: его тело уходит на сервер потоком, где
# репозитория нет вовсе, — поэтому он вливает содержимое в тот же поток перед своим телом.
load_declared() {
  local file="$1" line key value
  while IFS= read -r line || [[ -n "$line" ]]; do
    [[ "$line" =~ ^[[:space:]]*(#.*)?$ ]] && continue
    key="${line%%=*}"
    value="${line#*=}"
    if [[ "$value" == \"*\" && "$value" == *\" ]]; then
      value="${value#\"}"
      value="${value%\"}"
    elif [[ "$value" == \'*\' && "$value" == *\' ]]; then
      value="${value#\'}"
      value="${value%\'}"
    fi
    printf -v "$key" '%s' "$value"
  done <"$file"
}
